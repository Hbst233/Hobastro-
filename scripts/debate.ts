function runRole(roleTitle: string, promptText: string): Promise<string> {
  return new Promise((resolve, reject) => {
    console.log(`\n========================================`);
    console.log(`${roleTitle}`);
    console.log(`========================================\n`);

    const child = spawn('opencode', ['run', '-m', 'google/gemini-3.5-flash-lite', promptText], {
      stdio: ['inherit', 'pipe', 'pipe']
    });

    let stdoutData = '';
    let stderrData = '';
    let finished = false;
    let timedOut = false;

    const timeoutMs = 90000;
    let sigkillTimer: NodeJS.Timeout | null = null;

    const timer = setTimeout(() => {
      if (finished) return;
      timedOut = true;
      console.error(`Error running ${roleTitle}: timeout after ${timeoutMs}ms`);
      child.kill('SIGTERM');
      sigkillTimer = setTimeout(() => {
        if (!finished) {
          child.kill('SIGKILL');
        }
      }, 5000);
    }, timeoutMs);

    const cleanup = () => {
      clearTimeout(timer);
      if (sigkillTimer) clearTimeout(sigkillTimer);
    };

    child.stdout.on('data', (chunk) => {
      const str = chunk.toString();
      stdoutData += str;
      process.stdout.write(str);
    });

    child.stderr.on('data', (chunk) => {
      const str = chunk.toString();
      stderrData += str;
    });

    child.on('error', (err) => {
      if (finished) return;
      finished = true;
      cleanup();
      reject(new Error(`Error running ${roleTitle}: ${err.message}`));
    });

    child.on('close', (code, signal) => {
      if (finished) return;
      finished = true;
      cleanup();

      if (stderrData.trim()) {
        process.stderr.write(stderrData);
      }

      if (timedOut) {
        reject(new Error(`Error running ${roleTitle}: timeout`));
        return;
      }

      if (code !== 0 || signal) {
        const reason = signal ? `signal ${signal}` : `exit code ${code}`;
        reject(new Error(`Error running ${roleTitle}: ${reason}`));
        return;
      }

      const trimmed = stdoutData.trim();
      if (!trimmed) {
        reject(new Error(`Error running ${roleTitle}: empty response`));
        return;
      }

      resolve(stdoutData);
    });
  });
}

